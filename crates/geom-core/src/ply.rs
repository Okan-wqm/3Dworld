//! Binary little-endian PLY writer for colored point clouds.
//!
//! Replaces the GPL-licensed `plyfile` Python package that TRELLIS would otherwise
//! pull in (see LICENSES.md).

use glam::Vec3;

/// Writes points (already in the desired convention) with optional RGB colors.
/// Non-finite points are skipped.
pub fn write_ply_points(points: &[Vec3], colors: Option<&[[u8; 3]]>) -> Vec<u8> {
    let keep: Vec<usize> = (0..points.len())
        .filter(|&i| points[i].is_finite())
        .collect();
    let mut header = format!(
        "ply\nformat binary_little_endian 1.0\ncomment generated by 3Dworld geom-core\n\
         element vertex {}\nproperty float x\nproperty float y\nproperty float z\n",
        keep.len()
    );
    if colors.is_some() {
        header.push_str("property uchar red\nproperty uchar green\nproperty uchar blue\n");
    }
    header.push_str("end_header\n");

    let stride = 12 + if colors.is_some() { 3 } else { 0 };
    let mut out = Vec::with_capacity(header.len() + keep.len() * stride);
    out.extend_from_slice(header.as_bytes());
    for i in keep {
        for c in points[i].to_array() {
            out.extend_from_slice(&c.to_le_bytes());
        }
        if let Some(cols) = colors {
            out.extend_from_slice(&cols[i]);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn header_and_payload_sizes() {
        let pts = [Vec3::ONE, Vec3::NAN, Vec3::ZERO];
        let cols = [[255, 0, 0], [0, 255, 0], [0, 0, 255]];
        let ply = write_ply_points(&pts, Some(&cols));
        let text = String::from_utf8_lossy(&ply);
        assert!(text.contains("element vertex 2\n"));
        let header_len = text.find("end_header\n").unwrap() + "end_header\n".len();
        assert_eq!(ply.len() - header_len, 2 * 15);
        // Last point's color is blue.
        assert_eq!(&ply[ply.len() - 3..], &[0, 0, 255]);
    }
}
